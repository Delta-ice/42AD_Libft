#include "libft.h"

char	*ft_strdup(const char *s)
{
	size_t	len;
	char	*p;
	size_t	i;

	i = 0;
	len = ft_strlen(s);
	p = (char *) malloc(len + 1);
	if (!p)
		return (NULL);
	while (s[i] != '\0')
	{
		p[i] = s[i];
		i++;
	}
	p[i] = '\0';
	return (p);
}
